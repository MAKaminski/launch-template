#!/usr/bin/env tsx
/**
 * pnpm init:launch
 *
 * Turns this template into a specific launch. Interactive by default:
 *
 *     pnpm init:launch
 *
 * Non-interactive, for scripted use:
 *
 *     pnpm init:launch --name "Test #1 Repo" --slug test-1-repo --yes
 *
 * Idempotent: re-running produces the same result. Writes `.launch-initialized`
 * and warns before overwriting an already-initialised repo.
 */

import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline/promises";
import { stdin, stdout } from "node:process";

const ROOT = process.cwd();
const MARKER = path.join(ROOT, ".launch-initialized");

/** The join key across PostHog, Supabase and Stripe. Validated hard. */
const SLUG_PATTERN = /^[a-z][a-z0-9-]{2,31}$/;

const INTEGRATION_KEYS = ["posthog", "supabase", "stripe", "cal", "seo"] as const;
type IntegrationKey = (typeof INTEGRATION_KEYS)[number];

interface Answers {
  name: string;
  slug: string;
  tagline: string;
  domain: string | null;
  integrations: Record<IntegrationKey, boolean>;
}

// ── argv ─────────────────────────────────────────────────────────────────────

function parseArgs(argv: string[]): Map<string, string | boolean> {
  const args = new Map<string, string | boolean>();
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token?.startsWith("--")) continue;
    const key = token.slice(2);
    const next = argv[i + 1];
    if (next && !next.startsWith("--")) {
      args.set(key, next);
      i += 1;
    } else {
      args.set(key, true);
    }
  }
  return args;
}

// ── validation ───────────────────────────────────────────────────────────────

export function slugify(input: string): string {
  return input
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-")
    .slice(0, 32)
    .replace(/-+$/g, "");
}

export function validateSlug(slug: string): string | null {
  if (!SLUG_PATTERN.test(slug)) {
    return `"${slug}" is not a valid slug. Must be 3–32 chars, start with a letter, and contain only lowercase letters, digits and hyphens.`;
  }
  if (slug.endsWith("-")) return "Slug must not end with a hyphen.";
  return null;
}

/** Postgres schema names cannot contain hyphens. */
export function schemaFor(slug: string): string {
  return `launch_${slug.replace(/-/g, "_")}`;
}

/** IndexNow requires 8–128 chars of hex. */
export function generateIndexNowKey(): string {
  return randomBytes(16).toString("hex");
}

// ── file helpers ─────────────────────────────────────────────────────────────

function read(file: string): string {
  return fs.readFileSync(path.join(ROOT, file), "utf8");
}

function write(file: string, contents: string): void {
  const target = path.join(ROOT, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, contents, "utf8");
}

function exists(file: string): boolean {
  return fs.existsSync(path.join(ROOT, file));
}

// ── the rewrites ─────────────────────────────────────────────────────────────

/**
 * Renders launch.config.ts in full.
 *
 * Deliberately generated rather than regex-patched. Patching looked simpler,
 * but the `integrations: {` pattern matches the LaunchConfig *interface* before
 * it matches the object literal — so a non-greedy replace silently swallowed
 * the entire `export const launchConfig` declaration and produced a file that
 * did not compile. Emitting the whole file is deterministic, idempotent, and
 * cannot corrupt what it does not read.
 */
function renderLaunchConfig(answers: Answers, plans: string): string {
  const integrations = INTEGRATION_KEYS.map(
    (key) => `    ${key}: ${answers.integrations[key]},`,
  ).join("\n");

  return `/**
 * Per-launch configuration — the source of truth for this launch's identity.
 *
 * Generated by \`pnpm init:launch\`. Everything here is public and safe to
 * bundle into the client; secrets live in .env.local and never appear here.
 *
 * \`slug\` is the join key across all three shared platforms:
 *   PostHog  → registered as the \`launch_slug\` super property on every event
 *   Supabase → the Postgres schema name, \`launch_<slug>\`
 *   Stripe   → \`metadata.launch_slug\` on Products, Sessions and PaymentIntents
 * Changing it after launch orphans your data in all three. Don't.
 */

export type PlanInterval = "one_time" | "month" | "year";

export interface PricingPlan {
  /** Stable key the client sends to /api/checkout. NEVER a price ID. */
  key: string;
  name: string;
  description: string;
  /**
   * Stripe Price ID (price_...). The server maps \`key\` → \`priceId\`; the client
   * never sends a price or an amount, so a tampered request cannot change what
   * is charged. Read from the environment because test-mode and live-mode IDs
   * differ. Null renders the plan's button disabled.
   */
  priceId: string | null;
  /** Display only. Stripe is authoritative for what actually gets charged. */
  amountCents: number;
  currency: string;
  interval: PlanInterval;
  features: string[];
  highlighted?: boolean;
}

export interface LaunchConfig {
  slug: string;
  name: string;
  tagline: string;
  /** Bare hostname, no protocol. Null until a domain is attached. */
  domain: string | null;
  /** Which integrations this launch opted into at init time. */
  integrations: {
    posthog: boolean;
    supabase: boolean;
    stripe: boolean;
    cal: boolean;
    seo: boolean;
  };
  plans: PricingPlan[];
}

/**
 * Price IDs come straight from the environment rather than through lib/env
 * (which imports this file — the dependency only goes one way). \`pnpm
 * init:launch\` writes unset secrets as \`TODO_<NAME>\`, so those must read as
 * absent here too, or a plan renders an enabled button that fails at checkout.
 */
function priceId(value: string | undefined): string | null {
  if (!value || value.trim() === "" || value.startsWith("TODO_")) return null;
  return value.trim();
}

export const launchConfig: LaunchConfig = {
  slug: "${answers.slug}",
  name: "${escapeQuotes(answers.name)}",
  tagline: "${escapeQuotes(answers.tagline)}",
  domain: ${answers.domain ? `"${answers.domain}"` : "null"},

  integrations: {
${integrations}
  },

  plans: ${plans},
};

/** Postgres schema for this launch. Matches the generated migration. */
export const dbSchema = \`launch_\${launchConfig.slug.replace(/-/g, "_")}\`;

export function getPlan(key: string): PricingPlan | undefined {
  return launchConfig.plans.find((plan) => plan.key === key);
}

export default launchConfig;
`;
}

